/** Builds the script.md text that the user takes to Claude Code. */
fun buildScript(
    title: String,
    isCode: Boolean,
    content: String,
    vertical: Boolean,
    selectedEffects: List<EffectDef>
): String {
    val canvasLine = if (vertical) {
        "1080x1920 (9:16 Shorts), 30 fps"
    } else {
        "1920x1080 (16:9 Long), 30 fps"
    }
    val fxLines = if (selectedEffects.isEmpty()) {
        "- (koi select nahi — catalog se munasib effects khud chuno)"
    } else {
        selectedEffects.joinToString("\n") { "- ${it.id} (${it.name})" }
    }
    return """
# CodeMotion Script — $title

## Repo
brpportal/codemotion — is repo ki catalog/effects.json aur docs/FORMAT_SPEC.md hi
qanoon hai. Sirf wahi effect IDs istemal karo jo catalog me hain.

## Canvas
$canvasLine

## Target Effects (sirf yehi istemal karo)
$fxLines

## Content Type
${if (isCode) "Code" else "Script"}

## Content
$content

## Tumhara Kaam
Upar diye gaye content se ek motion-graphics video ki project.json file banao.
Rules:
- Sirf catalog (brpportal/codemotion) ke effect IDs istemal karo.
- Koi scene 3 second se zyada static nahi; har 2-3s me harkat ya naya layer.
- Pehla scene hook ho (shocking fact / bold claim / sawal). "Hello dosto" kabhi nahi.
- Timing hamesha ms me; layers scene ki duration ke andar rakho.
- Ek layer me text 2-6 alfaz se zyada nahi; colors high contrast (dark bg, white/yellow text).
- Sirf project.json file return karo — koi extra file ya code nahi.

project.json schema (summary):
canvas: { w, h, fps }
scenes: [ { id, durationMs, layers: [ {
  id, type (text/code/card/image/highlight), effect (catalog ID),
  startMs, durationMs, x, y, w, h,
  text, code, color (#RRGGBB), bg (#AARRGGBB), fontSize
} ] } ]
Layers ki order hi z-order hai (pehla = sab se neeche).
""".trimIndent()
}

@Composable
fun NewScriptScreen(
    effects: List<EffectDef>,
    selectedIds: List<String>,
    onBack: () -> Unit
) {
    val context = LocalContext.current
    var title by remember { mutableStateOf("") }
    var isCode by remember { mutableStateOf(true) }
    var content by remember { mutableStateOf("") }
    var vertical by remember { mutableStateOf(true) }
    var generated by remember { mutableStateOf("") }
    var savedMsg by remember { mutableStateOf<String?>(null) }

    val saveLauncher = rememberLauncherForActivityResult(
        ActivityResultContracts.CreateDocument("text/markdown")
    ) { uri ->
        if (uri != null && generated.isNotEmpty()) {
            try {
                context.contentResolver.openOutputStream(uri)?.use {
                    it.write(generated.toByteArray(Charsets.UTF_8))
                }
                savedMsg = "script.md save ho gayi."
            } catch (e: Exception) {
                savedMsg = "Save error: ${e.message}"
            }
        }
    }

    val selectedFx = effects.filter { selectedIds.contains(it.id) }

    Column(
        Modifier
            .fillMaxSize()
            .padding(16.dp)
            .verticalScroll(rememberScrollState())
    ) {
        Row {
            Button(onClick = onBack) { Text("Back") }
            Spacer(Modifier.width(12.dp))
            Text(
                "New Script",
                style = MaterialTheme.typography.titleLarge,
                fontWeight = FontWeight.Bold
            )
        }
        Spacer(Modifier.height(14.dp))

        OutlinedTextField(
            value = title,
            onValueChange = { title = it },
            label = { Text("Title") },
            modifier = Modifier.fillMaxWidth()
        )
        Spacer(Modifier.height(10.dp))

        Text("Content type", fontWeight = FontWeight.Bold)
        Row {
            FilterChip(
                selected = isCode,
                onClick = { isCode = true },
                label = { Text("Code") }
            )
            Spacer(Modifier.width(8.dp))
            FilterChip(
                selected = !isCode,
                onClick = { isCode = false },
                label = { Text("Script / Topic") }
            )
        }
        Spacer(Modifier.height(10.dp))

        OutlinedTextField(
            value = content,
            onValueChange = { content = it },
            label = { Text(if (isCode) "Apna code yahan paste karo" else "Script / topic yahan likho") },
            modifier = Modifier.fillMaxWidth(),
            minLines = 6
        )
        Spacer(Modifier.height(10.dp))

        Text("Video format", fontWeight = FontWeight.Bold)
        Row {
            FilterChip(
                selected = vertical,
                onClick = { vertical = true },
                label = { Text("9:16 — 1080x1920") }
            )
            Spacer(Modifier.width(8.dp))
            FilterChip(
                selected = !vertical,
                onClick = { vertical = false },
                label = { Text("16:9 — 1920x1080") }
            )
        }
        Spacer(Modifier.height(10.dp))

        Text("Selected effects", fontWeight = FontWeight.Bold)
        Text(
            if (selectedFx.isEmpty()) {
                "Koi effect select nahi — pehle Effects Gallery se select karo (baghair selection ke bhi script ban jayegi)."
            } else {
                selectedFx.joinToString(", ") { it.id }
            },
            style = MaterialTheme.typography.bodySmall
        )
        Spacer(Modifier.height(14.dp))

        Button(
            onClick = {
                generated = buildScript(
                    title = title.ifBlank { "Untitled" },
                    isCode = isCode,
                    content = content,
                    vertical = vertical,
                    selectedEffects = selectedFx
                )
                savedMsg = null
            },
            modifier = Modifier.fillMaxWidth()
        ) {
            Text("Generate script.md")
        }

        if (generated.isNotEmpty()) {
            Spacer(Modifier.height(14.dp))
            OutlinedTextField(
                value = generated,
                onValueChange = {},
                readOnly = true,
                label = { Text("script.md") },
                modifier = Modifier.fillMaxWidth(),
                minLines = 10,
                maxLines = 16
            )
            Spacer(Modifier.height(10.dp))
            Row {
                Button(onClick = {
                    val intent = Intent(Intent.ACTION_SEND).apply {
                        type = "text/plain"
                        putExtra(Intent.EXTRA_TEXT, generated)
                    }
                    context.startActivity(Intent.createChooser(intent, "Share script.md"))
                }) {
                    Text("Share")
                }
                Spacer(Modifier.width(10.dp))
                Button(onClick = { saveLauncher.launch("codemotion-script.md") }) {
                    Text("Save file")
                }
            }
            if (savedMsg != null) {
                Spacer(Modifier.height(8.dp))
                Text(savedMsg!!, style = MaterialTheme.typography.bodySmall)
            }
        }
    }
}
